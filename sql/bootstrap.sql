-- CONTAVIA Cortex Search bootstrap.
-- Review names, warehouse size, target lag, model availability, and role assignments
-- before running this script in a Snowflake account.

USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS CONTAVIA_CORTEX_ADMIN
  COMMENT = 'Owns and refreshes CONTAVIA Cortex Search services';

CREATE ROLE IF NOT EXISTS CONTAVIA_RAG_APP
  COMMENT = 'Least-privilege runtime role for the CONTAVIA RAG application';

GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE CONTAVIA_CORTEX_ADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE CONTAVIA_RAG_APP;
GRANT ROLE CONTAVIA_CORTEX_ADMIN TO ROLE SYSADMIN;

USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS CONTAVIA;
CREATE SCHEMA IF NOT EXISTS CONTAVIA.KNOWLEDGE;

CREATE WAREHOUSE IF NOT EXISTS CONTAVIA_RAG_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Query and Cortex refresh warehouse for CONTAVIA RAG';

CREATE TABLE IF NOT EXISTS CONTAVIA.KNOWLEDGE.DOCUMENT_CHUNKS (
  CHUNK_ID VARCHAR NOT NULL,
  TITLE VARCHAR NOT NULL,
  CHUNK VARCHAR NOT NULL,
  SOURCE_URL VARCHAR,
  CATEGORY VARCHAR DEFAULT 'general',
  UPDATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_DOCUMENT_CHUNKS PRIMARY KEY (CHUNK_ID)
);

ALTER TABLE CONTAVIA.KNOWLEDGE.DOCUMENT_CHUNKS SET CHANGE_TRACKING = TRUE;

USE ROLE SECURITYADMIN;

GRANT USAGE ON DATABASE CONTAVIA TO ROLE CONTAVIA_CORTEX_ADMIN;
GRANT USAGE ON SCHEMA CONTAVIA.KNOWLEDGE TO ROLE CONTAVIA_CORTEX_ADMIN;
GRANT CREATE CORTEX SEARCH SERVICE ON SCHEMA CONTAVIA.KNOWLEDGE
  TO ROLE CONTAVIA_CORTEX_ADMIN;
GRANT SELECT ON TABLE CONTAVIA.KNOWLEDGE.DOCUMENT_CHUNKS
  TO ROLE CONTAVIA_CORTEX_ADMIN;
GRANT USAGE ON WAREHOUSE CONTAVIA_RAG_WH TO ROLE CONTAVIA_CORTEX_ADMIN;

USE ROLE CONTAVIA_CORTEX_ADMIN;

CREATE OR REPLACE CORTEX SEARCH SERVICE CONTAVIA.KNOWLEDGE.DOCUMENT_SEARCH
  ON CHUNK
  PRIMARY KEY (CHUNK_ID)
  ATTRIBUTES CATEGORY
  WAREHOUSE = CONTAVIA_RAG_WH
  TARGET_LAG = '1 hour'
  REFRESH_MODE = INCREMENTAL
  AUTO_SUSPEND = 300
  REQUEST_LOGGING = FALSE
  COMMENT = 'Grounded document retrieval for the CONTAVIA RAG application'
  AS (
    SELECT
      CHUNK,
      CHUNK_ID,
      TITLE,
      SOURCE_URL,
      CATEGORY,
      UPDATED_AT
    FROM CONTAVIA.KNOWLEDGE.DOCUMENT_CHUNKS
  );

USE ROLE SECURITYADMIN;

GRANT USAGE ON WAREHOUSE CONTAVIA_RAG_WH TO ROLE CONTAVIA_RAG_APP;
GRANT USAGE ON DATABASE CONTAVIA TO ROLE CONTAVIA_RAG_APP;
GRANT USAGE ON SCHEMA CONTAVIA.KNOWLEDGE TO ROLE CONTAVIA_RAG_APP;
GRANT USAGE ON CORTEX SEARCH SERVICE CONTAVIA.KNOWLEDGE.DOCUMENT_SEARCH
  TO ROLE CONTAVIA_RAG_APP;

