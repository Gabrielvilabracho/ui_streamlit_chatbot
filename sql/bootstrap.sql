-- SOFIA Cortex Search bootstrap.
-- Review names, warehouse size, target lag, model availability, and role assignments
-- before running this script in a Snowflake account.

USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS SOFIA_CORTEX_ADMIN
  COMMENT = 'Owns and refreshes SOFIA Cortex Search services';

CREATE ROLE IF NOT EXISTS SOFIA_RAG_APP
  COMMENT = 'Least-privilege runtime role for the SOFIA RAG application';

GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE SOFIA_CORTEX_ADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE SOFIA_RAG_APP;
GRANT ROLE SOFIA_CORTEX_ADMIN TO ROLE SYSADMIN;

USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS SOFIA;
CREATE SCHEMA IF NOT EXISTS SOFIA.KNOWLEDGE;

CREATE WAREHOUSE IF NOT EXISTS SOFIA_RAG_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Query and Cortex refresh warehouse for SOFIA RAG';

CREATE TABLE IF NOT EXISTS SOFIA.KNOWLEDGE.DOCUMENT_CHUNKS (
  CHUNK_ID VARCHAR NOT NULL,
  TITLE VARCHAR NOT NULL,
  CHUNK VARCHAR NOT NULL,
  SOURCE_URL VARCHAR,
  CATEGORY VARCHAR DEFAULT 'general',
  UPDATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_DOCUMENT_CHUNKS PRIMARY KEY (CHUNK_ID)
);

ALTER TABLE SOFIA.KNOWLEDGE.DOCUMENT_CHUNKS SET CHANGE_TRACKING = TRUE;

USE ROLE SECURITYADMIN;

GRANT USAGE ON DATABASE SOFIA TO ROLE SOFIA_CORTEX_ADMIN;
GRANT USAGE ON SCHEMA SOFIA.KNOWLEDGE TO ROLE SOFIA_CORTEX_ADMIN;
GRANT CREATE CORTEX SEARCH SERVICE ON SCHEMA SOFIA.KNOWLEDGE
  TO ROLE SOFIA_CORTEX_ADMIN;
GRANT SELECT ON TABLE SOFIA.KNOWLEDGE.DOCUMENT_CHUNKS
  TO ROLE SOFIA_CORTEX_ADMIN;
GRANT USAGE ON WAREHOUSE SOFIA_RAG_WH TO ROLE SOFIA_CORTEX_ADMIN;

USE ROLE SOFIA_CORTEX_ADMIN;

CREATE OR REPLACE CORTEX SEARCH SERVICE SOFIA.KNOWLEDGE.DOCUMENT_SEARCH
  ON CHUNK
  PRIMARY KEY (CHUNK_ID)
  ATTRIBUTES CATEGORY
  WAREHOUSE = SOFIA_RAG_WH
  TARGET_LAG = '1 hour'
  REFRESH_MODE = INCREMENTAL
  AUTO_SUSPEND = 300
  REQUEST_LOGGING = FALSE
  COMMENT = 'Grounded document retrieval for the SOFIA RAG application'
  AS (
    SELECT
      CHUNK,
      CHUNK_ID,
      TITLE,
      SOURCE_URL,
      CATEGORY,
      UPDATED_AT
    FROM SOFIA.KNOWLEDGE.DOCUMENT_CHUNKS
  );

USE ROLE SECURITYADMIN;

GRANT USAGE ON WAREHOUSE SOFIA_RAG_WH TO ROLE SOFIA_RAG_APP;
GRANT USAGE ON DATABASE SOFIA TO ROLE SOFIA_RAG_APP;
GRANT USAGE ON SCHEMA SOFIA.KNOWLEDGE TO ROLE SOFIA_RAG_APP;
GRANT USAGE ON CORTEX SEARCH SERVICE SOFIA.KNOWLEDGE.DOCUMENT_SEARCH
  TO ROLE SOFIA_RAG_APP;

