-- Sof~IA evaluation data foundation.
-- Review role assignments and retention requirements before executing this script.
-- This script creates empty structures only: it does not load questions or schedule work.

USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS AGENT_PLATFORM
  COMMENT = 'Reusable Snowflake agent configuration and evaluation data';
CREATE SCHEMA IF NOT EXISTS AGENT_PLATFORM.EVALUATIONS
  COMMENT = 'Approved evaluation cases, run metadata, results, and reviewed feedback';

CREATE TABLE IF NOT EXISTS AGENT_PLATFORM.EVALUATIONS.EVALUATION_CASES (
  CASE_ID VARCHAR NOT NULL,
  QUESTION VARCHAR NOT NULL,
  EXPECTED_ANSWER VARCHAR,
  DOMAIN VARCHAR NOT NULL,
  POLICY VARCHAR NOT NULL,
  DIFFICULTY VARCHAR NOT NULL,
  SOURCE_KIND VARCHAR NOT NULL,
  APPROVED_FOR_EVALUATION BOOLEAN NOT NULL DEFAULT FALSE,
  APPROVED_BY VARCHAR,
  APPROVED_AT TIMESTAMP_TZ,
  CREATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  UPDATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_EVALUATION_CASES PRIMARY KEY (CASE_ID)
);

CREATE TABLE IF NOT EXISTS AGENT_PLATFORM.EVALUATIONS.EVALUATION_RUNS (
  RUN_ID VARCHAR NOT NULL,
  AGENT_VERSION VARCHAR NOT NULL,
  PROMPT_VERSION VARCHAR NOT NULL,
  MODEL VARCHAR NOT NULL,
  RETRIEVAL_CONFIGURATION VARIANT,
  BASELINE_RUN_ID VARCHAR,
  STARTED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  FINISHED_AT TIMESTAMP_TZ,
  REVIEWED_BY VARCHAR,
  APPROVED_AT TIMESTAMP_TZ,
  CONSTRAINT PK_EVALUATION_RUNS PRIMARY KEY (RUN_ID)
);

CREATE TABLE IF NOT EXISTS AGENT_PLATFORM.EVALUATIONS.EVALUATION_RESULTS (
  RUN_ID VARCHAR NOT NULL,
  CASE_ID VARCHAR NOT NULL,
  METRIC VARCHAR NOT NULL,
  SCORE NUMBER(10, 6),
  LATENCY_MILLISECONDS NUMBER(18, 3),
  INPUT_TOKENS NUMBER(18, 0),
  OUTPUT_TOKENS NUMBER(18, 0),
  COST_CREDITS NUMBER(18, 8),
  TRACE_REFERENCE VARCHAR,
  RECORDED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_EVALUATION_RESULTS PRIMARY KEY (RUN_ID, CASE_ID, METRIC)
);

CREATE TABLE IF NOT EXISTS AGENT_PLATFORM.EVALUATIONS.FEEDBACK_SAMPLES (
  FEEDBACK_ID VARCHAR NOT NULL,
  QUESTION VARCHAR NOT NULL,
  OUTCOME VARCHAR NOT NULL,
  REVIEWER_DECISION VARCHAR NOT NULL,
  APPROVED_FOR_EVALUATION BOOLEAN NOT NULL DEFAULT FALSE,
  REVIEWED_BY VARCHAR,
  REVIEWED_AT TIMESTAMP_TZ,
  CREATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_FEEDBACK_SAMPLES PRIMARY KEY (FEEDBACK_ID)
);

